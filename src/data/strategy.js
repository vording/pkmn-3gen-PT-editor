const hasMember = (names, slot) => (Array.isArray(slot) ? slot.some((n) => names.has(n)) : names.has(slot));

// members: 型つきのポケモン（{ name, set }）または名前の配列。型があるときは need（前提の技）も確認する
export function findCombos(members) {
  const list = [...members];
  const set = new Set(list.map((m) => (typeof m === 'string' ? m : m.name)));
  const ok = (c) => {
    if (!c.members.every((slot) => hasMember(set, slot))) return false;
    if (!c.need) return true;
    const m = list.find((x) => typeof x !== 'string' && x.name === c.need.name);
    return !m || m.set.moves.includes(c.need.move);
  };
  return { pairs: COMBOS.filter(ok), trios: TRIOS.filter(ok) };
}

