export function classifyArchetype(members) {
  const hasType = (t) => members.some((m) => m.types.includes(t));
  const steel = hasType('steel');
  const water = hasType('water');
  const zapdos = members.some((m) => m.name === 'サンダー');
  const fighting = hasType('fighting');
  if (steel && water && zapdos) return '鋼水サンダー';
  if (steel && water) return '鋼水';
  if (members.some((m) => m.name === 'メタグロス') && zapdos) return 'グロスサンダー';
  if (!steel && fighting && water) return '格闘水';
  return 'その他';
}

// 身代わり展開・バトンなど「コンボ」への対策になる要素
const MULTI_HIT = new Set(['ロックブラスト', 'ホネブーメラン', 'タネマシンガン', 'ダブルニードル', 'みだれづき', 'ダブルキック', 'にどげり']);
export function antiComboTools(m) {
  const out = [];
  const mv = m.set.moves;
  if (m.tags.phaze) out.push(mv.find((x) => ['ほえる', 'ふきとばし', 'ほろびのうた', 'くろいきり'].includes(x)));
  if (mv.includes('アンコール')) out.push('アンコール');
  if (mv.includes('ちょうはつ')) out.push('ちょうはつ');
  if (m.tags.explode) out.push(mv.find((x) => ['だいばくはつ', 'じばく', 'みちづれ', 'おきみやげ'].includes(x)));
  if (m.item === 'せんせいのツメ') out.push('せんせいのツメ');
  for (const x of mv) if (MULTI_HIT.has(x)) out.push(x);
  return out;
}
